enum CableType {
  /// --------------------------------------------------------------------------
  /// 60227 IEC 01
  /// --------------------------------------------------------------------------
  iec01(
    code: '60227 IEC 01',
    displayName: '60227 IEC 01',
  ),

  /// --------------------------------------------------------------------------
  /// 60227 IEC 02
  /// --------------------------------------------------------------------------
  iec02(
    code: '60227 IEC 02',
    displayName: '60227 IEC 02',
  ),

  /// --------------------------------------------------------------------------
  /// 60227 IEC 05
  /// --------------------------------------------------------------------------
  iec05(
    code: '60227 IEC 05',
    displayName: '60227 IEC 05',
  ),

  /// --------------------------------------------------------------------------
  /// 60227 IEC 06
  /// --------------------------------------------------------------------------
  iec06(
    code: '60227 IEC 06',
    displayName: '60227 IEC 06',
  ),

  /// --------------------------------------------------------------------------
  /// 60227 IEC 10
  /// --------------------------------------------------------------------------
  iec10(
    code: '60227 IEC 10',
    displayName: '60227 IEC 10',
  ),

  /// --------------------------------------------------------------------------
  /// NYY
  /// --------------------------------------------------------------------------
  nyy(
    code: 'NYY',
    displayName: 'NYY',
  ),

  /// --------------------------------------------------------------------------
  /// NYY-G
  /// --------------------------------------------------------------------------
  nyyG(
    code: 'NYY-G',
    displayName: 'NYY-G',
  ),

  /// --------------------------------------------------------------------------
  /// VCT
  /// --------------------------------------------------------------------------
  vct(
    code: 'VCT',
    displayName: 'VCT',
  ),

  /// --------------------------------------------------------------------------
  /// VCT-G
  /// --------------------------------------------------------------------------
  vctG(
    code: 'VCT-G',
    displayName: 'VCT-G',
  ),

  /// --------------------------------------------------------------------------
  /// IEC 60502-1
  /// --------------------------------------------------------------------------
  iec605021(
    code: 'IEC 60502-1',
    displayName: 'IEC 60502-1',
  );

  /// ชื่อที่ใช้เก็บในฐานข้อมูล
  final String code;

  /// ชื่อที่ใช้แสดงบนหน้าจอ
  final String displayName;

  const CableType({
    required this.code,
    required this.displayName,
  });

  /// ========================================================================
  /// ค้นหา Enum จาก Code
  /// ========================================================================
  static CableType fromCode(String code) {
    return CableType.values.firstWhere(
      (e) => e.code == code,
      orElse: () => CableType.iec01,
    );
  }

  @override
  String toString() => displayName;
}